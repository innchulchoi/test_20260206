def P(text, style=st_body):
    return Paragraph(text, style)

def bullets(items, style=st_bullet, bcolor=ACCENT):
    lf = []
    for it in items:
        lf.append(ListItem(Paragraph(it, style), leftIndent=6, value=None))
    return ListFlowable(
        [ListItem(Paragraph(i, style)) for i in items],
        bulletType="bullet", bulletColor=bcolor, bulletFontSize=7,
        leftIndent=14, bulletOffsetY=1, spaceBefore=2, spaceAfter=6,
    )

def spacer(h=6):
    return Spacer(1, h)

def caption(text):
    return P(text, st_caption)

def case_study(number, title, paras, tag="사례 연구"):
    flow = []
    flow.append(P("%s %s" % (tag, number), st_case_tag))
    flow.append(P(title, st_case_h))
    for pr in paras:
        if isinstance(pr, list):
            flow.append(bullets(pr))
        else:
            flow.append(P(pr, S("casebody", fontSize=9.3, leading=14, alignment=TA_JUSTIFY, spaceAfter=5)))
    inner = Table([[flow]], colWidths=[16.0*cm])
    inner.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,-1), CASEBG),
        ("BOX", (0,0), (-1,-1), 0.5, ACCENT),
        ("LEFTPADDING", (0,0), (-1,-1), 12),
        ("RIGHTPADDING", (0,0), (-1,-1), 12),
        ("TOPPADDING", (0,0), (-1,-1), 10),
        ("BOTTOMPADDING", (0,0), (-1,-1), 10),
        ("LINEBEFORE", (0,0), (0,-1), 3, ACCENT),
    ]))
    return KeepTogether([spacer(4), inner, spacer(6)])

def make_table(header, rows, col_widths, header_bg=WEF_BLUE, zebra=True):
    data = []
    data.append([P(h, st_th) for h in header])
    for r in rows:
        data.append([P(c, st_td_b) if i == 0 else P(c, st_td) for i, c in enumerate(r)])
    t = Table(data, colWidths=col_widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0,0), (-1,0), header_bg),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("LEFTPADDING", (0,0), (-1,-1), 6),
        ("RIGHTPADDING", (0,0), (-1,-1), 6),
        ("TOPPADDING", (0,0), (-1,-1), 5),
        ("BOTTOMPADDING", (0,0), (-1,-1), 5),
        ("GRID", (0,0), (-1,-1), 0.4, colors.HexColor("#c9d3e0")),
        ("LINEBELOW", (0,0), (-1,0), 0.8, header_bg),
    ]
    if zebra:
        for i in range(1, len(data)):
            if i % 2 == 0:
                style.append(("BACKGROUND", (0,i), (-1,i), LIGHT))
    t.setStyle(TableStyle(style))
    return t

def info_box(title, paras, bg=BOXBG, bar=WEF_BLUE):
    flow = []
    if title:
        flow.append(P(title, S("boxh", fontName="NanumB", fontSize=10, leading=14, textColor=bar, spaceAfter=4)))
    for pr in paras:
        if isinstance(pr, list):
            flow.append(bullets(pr))
        else:
            flow.append(P(pr, S("boxbody", fontSize=9.2, leading=13.5, alignment=TA_JUSTIFY, spaceAfter=4)))
    inner = Table([[flow]], colWidths=[16.0*cm])
    inner.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,-1), bg),
        ("LEFTPADDING", (0,0), (-1,-1), 12),
        ("RIGHTPADDING", (0,0), (-1,-1), 12),
        ("TOPPADDING", (0,0), (-1,-1), 9),
        ("BOTTOMPADDING", (0,0), (-1,-1), 9),
        ("LINEBEFORE", (0,0), (0,-1), 3, bar),
    ]))
    return KeepTogether([spacer(3), inner, spacer(5)])

